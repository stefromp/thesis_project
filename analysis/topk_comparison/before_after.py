#!/usr/bin/env python3
"""Before/after the categorical-input fix: utility and pair trends per rule.

    python3 analysis/topk_comparison/before_after.py

Inputs (run these first):
  after   compare_topk.py                                   -> OUT/
          dependency_fidelity.py                            -> analysis/dependency_fidelity/
  before  COMPARE_TOPK_VARIANT=legacy COMPARE_TOPK_OUT=<OUT>/before_catfix compare_topk.py
          COMPARE_TOPK_VARIANT=legacy DEPFID_OUT=<depfid>/before_catfix dependency_fidelity.py

Writes BEFORE_AFTER.md and before_after.csv in OUT. Rule order per dataset is
by mean; a pairwise outcome (win/tie/loss) is from the 95% CI in deltas.csv.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

import compare_topk as ct

DEP = ct.REPO / "analysis" / "dependency_fidelity"
RUNS = {"before": (ct.OUT / "before_catfix", DEP / "before_catfix"), "after": (ct.OUT, DEP)}
SHORT = {"fixed": "F", "jenks": "J", "entmax15": "E"}


def load():
    util, dep, dl, ddl, acr, dacr = {}, {}, {}, {}, {}, {}
    for k, (o, d) in RUNS.items():
        util[k] = pd.read_csv(o / "per_dataset_metrics.csv")
        dl[k] = pd.read_csv(o / "deltas.csv")
        acr[k] = pd.read_csv(o / "across_datasets.csv")
        dep[k] = pd.read_csv(d / "per_dataset.csv")
        ddl[k] = pd.read_csv(d / "deltas.csv")
        dacr[k] = pd.read_csv(d / "across_datasets.csv")
    cov = pd.read_csv(ct.OUT / "coverage.csv")
    return util, dep, dl, ddl, acr, dacr, cov


def order_str(vals: dict, sign: int) -> str:
    have = {r: v for r, v in vals.items() if np.isfinite(v)}
    if len(have) < 3:
        return "—"
    return " > ".join(SHORT[r] for r in sorted(have, key=lambda r: -sign * have[r]))


def main():
    util, dep, dl, ddl, acr, dacr, cov = load()
    info = cov.groupby("dataset").agg(prov=("provenance", "first"), variant=("variant", "first"),
                                      task=("task_type", "first"), ncat=("n_categorical", "first"))
    info = info[info.index.isin(util["after"].dataset)]
    info["subset"] = np.where(info.prov == "transfer", "held_out", "development")
    info = info.assign(_o=info.subset.map({"held_out": 0, "development": 1})).sort_values(["_o"]).drop(columns="_o")
    info = info.loc[sorted(info.index, key=lambda d: (info.loc[d, "subset"] != "held_out", d))]

    rows = []
    for ds, i in info.iterrows():
        for fam, src, metric, sign in (("utility", util, "score", 1), ("utility", util, "tabddpm_util", 1),
                                       ("dependency", dep, "column_pair_trends", 1)):
            for r in ct.RULES:
                rec = {"dataset": ds, "subset": i.subset, "variant_after": i.variant, "metric": metric, "rule": r}
                for k in RUNS:
                    d = src[k]
                    x = d[(d.dataset == ds) & (d.rule == r) & (d.metric == metric)]
                    rec[f"{k}_mean"] = x["mean"].iloc[0] if len(x) else np.nan
                    rec[f"{k}_sd"] = x["sd"].iloc[0] if len(x) else np.nan
                    rec[f"{k}_kind"] = (x["status"].iloc[0] if len(x) else "missing")
                rows.append(rec)
    T = pd.DataFrame(rows)
    T.to_csv(ct.OUT / "before_after.csv", index=False)

    L = ["# Before / after the categorical-input fix\n",
         "_Generated by `before_after.py` from the two `compare_topk.py` runs (`before_catfix/` = original "
         "trees for every dataset, `cat_input=log`; this directory = `*_catfix` for the 8 categorical datasets) "
         "and the two `dependency_fidelity.py` runs. Numerical-only datasets (california, diabetes, gesture, "
         "wilt, house) use the same runs in both columns; they are listed for completeness._\n",
         "Order: rules by mean (F = fixed, J = Jenks, E = entmax-1.5; first = best). The CI-based outcomes are "
         "in the pairwise table. Before, the fixed rule of a categorical ablated dataset (abalone, adult, buddy, "
         "churn2, insurance) is the grid summary (no samples → no pair trends, no per-seed CI).\n"]

    for metric, lab, fmt in (("score", "Primary utility: score (accuracy / −RMSE)", "{:.4f}"),
                             ("tabddpm_util", "Secondary utility: macro-F1 / R²", "{:.4f}"),
                             ("column_pair_trends", "Column Pair Trends (shared real bins; 1 = best)", "{:.4f}")):
        L.append(f"## {lab}\n")
        L.append("| dataset | subset | cat | fixed before → after | Jenks before → after | entmax before → after "
                 "| order before | order after | changed |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        for ds, i in info.iterrows():
            t = T[(T.dataset == ds) & (T.metric == metric)].set_index("rule")
            cells, ob, oa = [], {}, {}
            for r in ct.RULES:
                b, a = t.loc[r, "before_mean"], t.loc[r, "after_mean"]
                ob[r], oa[r] = b, a
                big = abs(a) >= 100
                f = "{:.1f}" if big else fmt
                bs = f.format(b) if np.isfinite(b) else "—"
                as_ = f.format(a) if np.isfinite(a) else "—"
                cells.append(bs if (i.variant != "catfix") else f"{bs} → {as_}")
            o_b, o_a = order_str(ob, 1), order_str(oa, 1)
            changed = "" if i.variant != "catfix" else ("**yes**" if o_b != o_a and o_b != "—" else
                                                        ("n/a" if o_b == "—" else "no"))
            L.append(f"| {ds} | {i.subset.replace('_', '-')} | {int(i.ncat)} | " + " | ".join(cells)
                     + f" | {o_b} | {o_a} | {changed} |")
        L.append("")

    L.append("## Across datasets: average rank (1 = best), before → after\n")
    L.append("| metric | subset | n before/after | fixed | Jenks | entmax-1.5 | Friedman p before → after |")
    L.append("|---|---|---|---|---|---|---|")
    for metric, src in (("score", acr), ("tabddpm_util", acr), ("column_pair_trends", dacr)):
        for sub, _, slab in ct.SUBSETS:
            got = {}
            for k in RUNS:
                a = src[k][(src[k].metric == metric) & (src[k].subset == sub)]
                rk = a[a.kind == "avg_rank"].set_index("a").value
                fp = a[a.kind == "friedman"].p_value
                got[k] = (rk, fp.iloc[0] if len(fp) else np.nan, int(a.n_datasets.iloc[0]) if len(a) else 0)
            if got["after"][2] == 0:
                continue
            cells = [f"{got['before'][0].get(r, np.nan):.2f} → {got['after'][0].get(r, np.nan):.2f}" for r in ct.RULES]
            fp = " → ".join(f"{got[k][1]:.3f}" if np.isfinite(got[k][1]) else "n/a" for k in RUNS)
            L.append(f"| {metric} | {slab} | {got['before'][2]}/{got['after'][2]} | " + " | ".join(cells) + f" | {fp} |")
    L.append("\nBefore, the development pair-trends ranks cover only the datasets with samples for all three rules "
             "(the 4 numerical ones); after, all 9.\n")

    L.append("## Pairwise outcomes per dataset (95% CI), before → after — categorical datasets\n")
    L.append("| dataset | subset | metric | Jenks vs fixed | entmax vs fixed | entmax vs Jenks |")
    L.append("|---|---|---|---|---|---|")
    for ds, i in info[info.variant == "catfix"].iterrows():
        for metric, src in (("score", dl), ("column_pair_trends", ddl)):
            cells = []
            for a, b in ct.PAIRS:
                o = []
                for k in RUNS:
                    d = src[k]
                    x = d[(d.dataset == ds) & (d.metric == metric) & (d.rule == a) & (d.vs == b)]
                    if not len(x):
                        o.append("—")
                        continue
                    x = x.iloc[0]
                    val = x.rel_delta_pct if metric == "score" else x.delta
                    unit = "%" if metric == "score" else ""
                    oc = x.outcome if not str(x.outcome).startswith("n/a") else "no CI"
                    o.append(f"{val:+.2f}{unit} {oc}" if metric == "score" and np.isfinite(val)
                             else (f"{val:+.4f} {oc}" if np.isfinite(val) else "—"))
                cells.append(" → ".join(o))
            L.append(f"| {ds} | {i.subset.replace('_', '-')} | {metric} | " + " | ".join(cells) + " |")
    L.append("")
    (ct.OUT / "BEFORE_AFTER.md").write_text("\n".join(L) + "\n")
    print(f"wrote {ct.rel(ct.OUT / 'BEFORE_AFTER.md')}")


if __name__ == "__main__":
    main()
